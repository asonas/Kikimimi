import assert from 'node:assert/strict';
import { samplePeakDBFS, MeterBallistics, fixturePCM } from './meter.mjs';
const samples = new Float32Array(800);
for(let i=0;i<samples.length;i++) samples[i]=10**(-18/20)*Math.sin(2*Math.PI*200*i/16000);
assert.ok(Math.abs(samplePeakDBFS(samples)+18)<0.001, 'A calibrated −18 dBFS sine must read −18');
assert.equal(samplePeakDBFS(new Float32Array(800)), -120, 'Silence must not produce activity');
assert.equal(samplePeakDBFS([NaN, Infinity, 0]), -120, 'Nonfinite samples must not poison the meter');
const meter = new MeterBallistics();
assert.equal(meter.frame(-18,0).level,-18,'Attack must be immediate');
for(let t=16;t<=784;t+=16) meter.frame(-60,t);
assert.equal(meter.peak,-18,'Peak must remain visible for 800ms');
const after=meter.frame(-60,816);
assert.ok(after.peak < -18,'Peak must decay after the hold');
assert.ok(Math.abs(after.level-(-37.584))<0.001,'Release must reflect elapsed time, not number of frames');
assert.equal(meter.frame(-30,832,{stale:true}).stale,true);
assert.equal(meter.level,-60,'An interrupted source must clear old readings');
assert.equal(meter.frame(-35,850,{reducedMotion:true}).level,-35);
assert.equal(samplePeakDBFS(fixturePCM(2,0,'silence')),-120);
console.log('8 meter behavior checks passed.');
